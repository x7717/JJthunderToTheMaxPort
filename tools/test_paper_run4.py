#!/usr/bin/env python3
"""Run 4: boot Paper 26.3 build 230 on the run3 world, execute /jjverify, capture the report."""
import subprocess, threading, time, os, re, sys, shutil

BASE = '/home/z/my-project/JJthunderToTheMaxPort'
SRV = f'{BASE}/paper-server'
JDK = '/home/z/my-project/tools/jdk-25.0.5+8/bin/java'
LOG = f'{BASE}/logs/run4-paper-jjverify.log'

os.makedirs(f'{SRV}/plugins', exist_ok=True)
shutil.copy(f'{BASE}/JJVerify-1.0.0.jar', f'{SRV}/plugins/JJVerify-1.0.0.jar')
with open(f'{SRV}/eula.txt', 'w') as f: f.write('eula=true\n')
if not os.path.isdir(f'{SRV}/world'):
    shutil.copytree(f'{BASE}/test-server/world', f'{SRV}/world')   # world generated by run3
with open(f'{SRV}/server.properties', 'w') as f:
    f.write('''online-mode=false
level-seed=JJThunder263Port
view-distance=4
simulation-distance=4
spawn-protection=0
max-tick-time=-1
sync-chunk-writes=false
motd=JJVerify paper check
''')

raw = []
def tag(m):
    line = f'[driver {time.strftime("%H:%M:%S")}] {m}'
    raw.append(line); print(line)

proc = subprocess.Popen([JDK, '-Xms512M', '-Xmx2304M', '-jar', 'paper-26.3-230.jar', 'nogui'],
                        cwd=SRV, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                        stderr=subprocess.STDOUT, text=True, bufsize=1)
def reader():
    for line in proc.stdout: raw.append(line.rstrip())
threading.Thread(target=reader, daemon=True).start()

def clean(t):
    t = t.replace('\r', '\n'); t = re.sub(r'\x1b\[[0-9;]*m', '', t)
    return [l.strip() for l in t.split('\n') if l.strip()]
def lines(): return clean('\n'.join(raw))
def wait_for(p, timeout, what):
    t0 = time.time()
    while time.time() - t0 < timeout:
        for l in lines():
            if re.search(p, l): tag(f'  => {l[:150]}'); return l
        time.sleep(2)
    tag(f'  !! TIMEOUT {what}'); return None
def send(c):
    tag(f'$ {c}'); proc.stdin.write(c + '\n'); proc.stdin.flush()

tag('RUN4: Paper 26.3 build 230 + JJVerify')
wait_for(r'Done \(|Done!', 600, 'paper boot') or (send('stop'), sys.exit(1))

send('jjverify')
rep = wait_for(r'JJVerify finished', 240, 'jjverify report')
wait_for(r'PASS -|FAIL -', 30, 'summary line')
time.sleep(3)
send('save-all')
time.sleep(5)
send('stop')
try: proc.wait(timeout=240)
except subprocess.TimeoutExpired: proc.kill()
tag('server stopped')

with open(LOG, 'w') as f: f.write('\n'.join(lines()) + '\n')
tag(f'log saved: {LOG}')

# copy the plugin's json report into logs/
rp = f'{SRV}/plugins/JJVerify/jjverify-report.json'
if os.path.exists(rp):
    shutil.copy(rp, f'{BASE}/logs/jjverify-report.json')
    tag('=== jjverify-report.json ===')
    print(open(f'{BASE}/logs/jjverify-report.json').read())
else:
    tag('no jjverify-report.json produced!')
